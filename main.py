"""NEXUS Command Center — local launcher and demo seed.

Runs the full local vertical slice:
- SQLite store (state/, nexus.db)
- Engine with worker pool
- HTTP API + dark ops console

Usage:
    python main.py            # start server on http://127.0.0.1:4820
    python main.py --fresh    # reset demo data first
    python main.py --seed     # seed identity agents + a few synthetic tasks

This is a local-only application. It does not deploy, restart, or alter any
DavidLab service.
"""

from __future__ import annotations

import argparse
import os
import sys
import time

BASE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BASE)

from nexus_cc.store import Store
from nexus_cc.adapters.registry import load_builtin_registry
from nexus_cc.engine.engine import Engine
from nexus_cc.httpd.server import app


DEFAULT_DB = os.path.join(BASE, "state", "nexus.db")
DEFAULT_HOST = "127.0.0.1"
DEFAULT_PORT = 4820


def seed(store: Store, engine: Engine) -> None:
    """Seed identity + a small, honest synthetic workload. No fake data."""
    store.register_agent(
        "lennox", "lennox", "LENNOX",
        description="Human commander and final authority. Not an execution worker.",
        capabilities=["decide", "approve"], requires_approval=False,
    )
    store.register_agent(
        "alistair", "alistair", "ALISTAIR",
        description=("Owner's right-hand agent: observes, evidences, correlates, "
                     "briefs, hands off. Cannot execute high-impact engineering."),
        capabilities=["observe", "evidence", "brief", "handoff"],
    )
    store.register_agent(
        "nexus", "nexus", "NEXUS",
        description=("Execution specialist: performs authorized, bounded "
                     "engineering. Cannot grant its own approvals."),
        capabilities=["execute", "implement", "test", "verify"],
        requires_approval=True,
    )

    # A few synthetic tasks to demonstrate control-plane behavior with real state.
    # Each is explicitly SIMULATED provenance and safely runnable by the engine.
    engine.submit(
        title="Synthetic inspect: weekly anomaly scan",
        objective="Run a bounded read-only inspection over a synthetic fixture.",
        acceptance="Inspection returns structured findings with provenance.",
        scope="observe fixture only",
        forbidden="no writes, no network, no shell",
        agent_id="alistair", adapter="inspector",
        payload={"target": "fixture/logs.txt",
                 "checks": ["heartbeat present", "timeouts under threshold",
                            "errors empty"]},
        creator="lennox", idempotency_key="seed-inspect-1",
    )
    engine.submit(
        title="Synthetic engineering: echo round trip",
        objective="Prove the worker/adapter/usage path with a deterministic echo.",
        scope="echo adapter only",
        agent_id="nexus", adapter="echo",
        payload={"message": "NEXUS Command Center vertical slice"},
        creator="alistair", idempotency_key="seed-echo-1",
    )
    engine.submit(
        title="Synthetic report (approval-gated)",
        objective="Write a small artifact; requires human approval before running.",
        acceptance="Artifact exists under the engine workspace with sha256.",
        scope="artifact:write under engine workspace",
        forbidden="no paths outside engine workspace",
        agent_id="nexus", adapter="artifact",
        payload={"filename": "readiness-report.md", "kind": "report",
                 "body": "Generated by NEXUS Command Center local demo."},
        approval_mode="required",
        creator="lennox", idempotency_key="seed-artifact-1",
    )


def main() -> int:
    ap = argparse.ArgumentParser(description="NEXUS Command Center")
    ap.add_argument("--host", default=DEFAULT_HOST)
    ap.add_argument("--port", type=int, default=DEFAULT_PORT)
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--fresh", action="store_true",
                    help="remove existing database first")
    ap.add_argument("--seed", action="store_true",
                    help="seed identity agents and synthetic demo tasks")
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()

    if args.fresh and os.path.exists(args.db):
        os.remove(args.db)
    os.makedirs(os.path.dirname(args.db), exist_ok=True)

    store = Store(args.db)
    registry = load_builtin_registry()
    engine = Engine(store, registry, workers=args.workers,
                    workspace=os.path.join(os.path.dirname(args.db), "workspace"))
    if args.seed:
        seed(store, engine)

    server = app(store, host=args.host, port=args.port, engine=engine,
                 auto_start_engine=True)
    print("=" * 62)
    print("NEXUS COMMAND CENTER  |  local vertical slice")
    print("=" * 62)
    print("  UI/API : http://%s:%d" % (args.host, args.port))
    print("  Store  : %s" % args.db)
    print("  Engine : %d workers" % args.workers)
    print("  Workspace: %s" % engine.workspace)
    print("  Ctrl+C to stop.")
    print("=" * 62)
    try:
        while True:
            time.sleep(3600)
    except KeyboardInterrupt:
        print("\nStopping...")
        engine.close()
        store.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
